  // Layout preferences (codex-layout:*, never session state). Reset layout —
  // in Map information or the app's More menu — restores their defaults.
  function pref(key, initial, onReset) {
    if (window.UILayout) return window.UILayout.remember(key, initial, onReset);
    var value = initial;
    return {
      get: function () {
        return value;
      },
      set: function (next) {
        value = next;
      },
    };
  }
