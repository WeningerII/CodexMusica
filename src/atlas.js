  function wireStack() {
    el.stack.addEventListener('click', function (e) {
      if (e.target.closest('[data-act="close"]')) {
        closeStack(true);
        return;
      }
      var row = e.target.closest('button[data-tid]');
      if (!row) return;
      var p = S.byId[row.dataset.tid];
      if (!p) return;
      closeStack();
      S.opener = null;
      select(p);
      flyTo(p);
    });
    el.stack.addEventListener('input', function (e) {
      if (e.target.id !== 'stack-filter') return;
      S.stack.filter = e.target.value;
      renderStackList();
    });
    // Roving focus so a long list is walkable without a mouse.
    el.stack.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') {
        e.stopPropagation();
        closeStack(true);
        return;
      }
      var rows = Array.prototype.slice.call(el.stack.querySelectorAll('button[data-tid]'));
      if (!rows.length) return;
      var i = rows.indexOf(document.activeElement);
      var next;
      if (e.key === 'ArrowDown') next = i < 0 ? 0 : (i + 1) % rows.length;
      else if (e.key === 'ArrowUp') next = i <= 0 ? rows.length - 1 : i - 1;
      else if (e.key === 'Home' && i >= 0) next = 0;
      else if (e.key === 'End' && i >= 0) next = rows.length - 1;
      else if (e.key === 'Enter' && e.target.id === 'stack-filter') next = 0;
      else return;
      e.preventDefault();
      rows[next].focus();
    });
  }

