  // ── search ──

  function onQuery() {
    var val = el.search.value;
    var ql = val.trim().toLowerCase();
    // Focusing an empty search must not erase the active collection filter.
    if (S.thread && !ql) {
      el.results.hidden = true;
      return;
    }
    if (S.thread) exitThread();
    var all = !ql
      ? []
      : S.pts.filter(function (p) {
          return (
            p.name.toLowerCase().indexOf(ql) >= 0 ||
            p.id.indexOf(ql.replace(/\s+/g, '_')) >= 0 ||
            p.place.toLowerCase().indexOf(ql) >= 0
          );
        });
    var ids = new Set(
      all.map(function (p) {
        return p.id;
      })
    );
    var tokenHit = null;
    if (ql.length >= 3) {
      var toks = Object.keys(S.tokenIdx).filter(function (t) {
        return t.indexOf(ql) >= 0;
      });
      if (toks.length) {
        var n = 0;
        toks.forEach(function (t) {
          S.tokenIdx[t].forEach(function (id) {
            if (!S.byId[id]) return;
            if (!ids.has(id)) n++;
            ids.add(id);
          });
        });
        tokenHit = { tokens: toks.slice(0, 3).join(', ') + (toks.length > 3 ? '…' : ''), count: n };
      }
    }
    S.qmatch = ql ? ids : null;

    var h = '';
    if (all.length)
      h +=
        '<div class="results-head">' +
        plural(all.length, 'name, place or id match', 'name, place or id matches') +
        (all.length > 12 ? ' · first 12 below, all lit on the map' : '') +
        '</div>';
    h += all
      .slice(0, 12)
      .map(function (p) {
        return (
          '<button class="rowbtn" type="button" data-tid="' +
          esc(p.id) +
          '">' +
          mark(p.root) +
          '<span class="rowtext"><span class="rowname">' +
          esc(p.name) +
          '</span><span class="rowplace">' +
          esc(p.place) +
          '</span></span></button>'
        );
      })
      .join('');
    if (tokenHit) {
      h +=
        '<div class="results-sound"><div class="label">Sound-word match</div>' +
        '<div class="results-tokens">' +
        esc(tokenHit.tokens) +
        '</div><div class="results-why">' +
        (tokenHit.count
          ? '+' +
            plural(tokenHit.count, 'more tradition') +
            ' lit on the map because a sound word in their recipe contains “' +
            esc(ql) +
            '” — matched by descriptor, not by name.'
          : 'These sound words belong to the traditions already listed.') +
        '</div></div>';
    }
    if (ql && !all.length && !tokenHit)
      h =
        '<div class="route-end" role="status">No matching genres or places for “' +
        esc(val.trim()) +
        '”. Try a place, a catalog id, or a sound word such as “drone”.</div>';
    el.results.innerHTML = h;
    el.results.hidden = !ql;
    syncControls();
    draw();
    scheduleListSync();
  }

