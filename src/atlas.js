// atlas.js — the Traditions Atlas: every placed tradition on an Equal Earth
// map, grouped by the catalog's own taxonomy roots rather than by geography.
//
// Loaded by atlas.html as a plain script (no build step — unlike codex.html,
// which is assembled by scripts/build_html.js because it inlines the catalog).
// The same file runs standalone and inside the app's Map view
// (atlas.html?embedded=1), where it asks the app to add a genre to Your recipe
// through postMessage and reports what actually arrived.
//
// TWO THINGS HERE ARE NOT IN THE ORIGINAL DESIGN, and they exist because the
// design could not be clicked:
//
//   1. Display coordinates come from data/atlas-geo.json, generated by
//      scripts/build_atlas_geo.js, which spreads co-located pins over a small
//      land-aware disc. data/geo.json puts many traditions on one coordinate,
//      so a stack projected to one screen point at every zoom.
//   2. openStack() — the location chooser. A bubble that cannot be zoomed apart
//      lists its members instead of zooming into a dead end. This is the floor
//      that makes every pin reachable no matter how deep the stack.
//
// See the header of scripts/build_atlas_geo.js for the measurements.
//
// COLOUR IS NEVER THE ONLY SIGNAL. There are more taxonomy roots than hues a
// reader can tell apart, so each root gets a (hue, shape) pair: seven palette
// hues from src/theme.css times circle / square / diamond / triangle. The
// map markers, the map key, the Genres list, the location chooser and every
// row draw the same pair from the same table, so a marker and its legend entry
// always agree, in either theme.

