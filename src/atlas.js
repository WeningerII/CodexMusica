  // Equal Earth projection.
  function proj(lat, lng) {
    var A1 = 1.340264,
      A2 = -0.081106,
      A3 = 0.000893,
      A4 = 0.003796,
      M = Math.sqrt(3) / 2;
    var la = (lat * Math.PI) / 180,
      lo = (lng * Math.PI) / 180;
    var t = Math.asin(M * Math.sin(la)),
      t2 = t * t,
      t6 = t2 * t2 * t2;
    return [
      (lo * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2))),
      t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2)),
    ];
  }

