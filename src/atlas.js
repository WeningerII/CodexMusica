  // Related results, with their basis: shared sound words when the catalog has
  // them for this tradition, otherwise a stated fallback (same classification
  // branch, nearest on the map). Neither is a claim of historical descent.
  function kinFor(p) {
    var sig = S.sigs[p.id];
    S.kinWhy = {};
    var ranked;
    if (sig) {
      var setOf = new Set(sig);
      ranked = Object.keys(S.sigs)
        .filter(function (id) {
          return id !== p.id && S.byId[id];
        })
        .map(function (id) {
          var other = S.sigs[id];
          var shared = [];
          for (var i = 0; i < other.length; i++) if (setOf.has(other[i])) shared.push(other[i]);
          return [id, shared.length / (setOf.size + other.length - shared.length), shared];
        })
        .filter(function (x) {
          return x[1] > 0.08;
        })
        .sort(function (a, b) {
          return b[1] - a[1];
        })
        .slice(0, 6)
        .map(function (x) {
          S.kinWhy[x[0]] = x[2];
          return x[0];
        });
    } else {
      var near = function (list) {
        return list
          .filter(function (q) {
            return q.id !== p.id;
          })
          .sort(function (a, b) {
            return Math.hypot(a.x - p.x, a.y - p.y) - Math.hypot(b.x - p.x, b.y - p.y);
          });
      };
      var sameNode = p.node
        ? near(
            S.pts.filter(function (q) {
              return q.node === p.node;
            })
          )
        : [];
      var sameRoot = near(
        S.pts.filter(function (q) {
          return q.root === p.root && (!p.node || q.node !== p.node);
        })
      );
      ranked = sameNode
        .concat(sameRoot)
        .slice(0, 6)
        .map(function (q) {
          return q.id;
        });
    }
    return ranked
      .map(function (id) {
        return S.byId[id];
      })
      .filter(Boolean);
  }

  function select(p) {
    if (!p) {
      S.sel = null;
      S.kin = [];
      S.recipeOpen = false;
      el.card.hidden = true;
      el.card.innerHTML = '';
      document.body.classList.remove('card-open');
      draw();
      syncList();
      syncFit();
      syncSide();
      return;
    }
    if (!S.sel || S.sel.id !== p.id) S.recipeOpen = false;
    S.kin = kinFor(p);
    S.sel = {
      id: p.id,
      name: p.name,
      place: p.place,
      root: p.root,
      branch: p.node ? branchNames(p.node) : ['Awaiting tree placement'],
      sigBasis: !!S.sigs[p.id],
      lineage: '',
      recipe: '',
      fetching: !S.cache[p.id],
      fetchError: false,
    };
    if (S.cache[p.id]) {
      S.sel.lineage = S.cache[p.id].lineage;
      S.sel.recipe = S.cache[p.id].recipe;
      S.sel.fetching = false;
    }
    renderCard();
    draw();
    syncList();
    syncFit();
    if (!S.cache[p.id]) fetchDetail(p.id);
  }

  function fetchDetail(id) {
    if (INLINE) {
      var d = INLINE.detail[id] || ['', ''];
      S.cache[id] = { lineage: d[0], recipe: d[1] };
      if (S.sel && S.sel.id === id) {
        S.sel.lineage = d[0];
        S.sel.recipe = d[1];
        S.sel.fetching = false;
        renderCard();
      }
      return;
    }
    // Relative, so a local checkout and a fork both read their own catalog.
    fetch('api/traditions/' + encodeURIComponent(id) + '.json')
      .then(function (r) {
        if (!r.ok) throw new Error(String(r.status));
        return r.json();
      })
      .then(function (d) {
        S.cache[id] = { lineage: d.lineage || '', recipe: d.recipe || '' };
      })
      .catch(function () {
        // Not cached: a transient failure should not poison the session, so
        // Retry (or the next click on this pin) tries again.
        if (S.sel && S.sel.id === id) {
          S.sel.fetchError = true;
          S.sel.fetching = false;
          renderCard();
        }
        throw null;
      })
      .then(function () {
        if (S.sel && S.sel.id === id && S.cache[id]) {
          S.sel.lineage = S.cache[id].lineage;
          S.sel.recipe = S.cache[id].recipe;
          S.sel.fetching = false;
          renderCard();
        }
      })
      .catch(function () {
        /* already surfaced above */
      });
  }

  function coordText(p) {
    var lat = Math.abs(p.lat).toFixed(2) + '°' + (p.lat >= 0 ? 'N' : 'S');
    var lng = Math.abs(p.lng).toFixed(2) + '°' + (p.lng >= 0 ? 'E' : 'W');
    return lat + ', ' + lng;
  }
  function coordStatus(id) {
    var has = function (v) {
      return Array.isArray(v) && v.indexOf(id) >= 0;
    };
    if (has(S.meta.verified)) return 'Human-verified.';
    if (has(S.meta.reviewed))
      return (
        'Model-reviewed' +
        (S.meta.reviewed_on ? ' on ' + esc(S.meta.reviewed_on) : '') +
        '; not yet verified by a person.'
      );
    if (typeof S.meta.reviewed === 'number')
      return (
        'This published copy carries review counts only: ' +
        S.meta.reviewed.toLocaleString('en') +
        ' model-reviewed, ' +
        metaCount(S.meta.verified).toLocaleString('en') +
        ' human-verified.'
      );
    return 'Drafted; neither model-reviewed nor human-verified.';
  }

