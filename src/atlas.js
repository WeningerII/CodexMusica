  function ingest(idx, geo, sigs, world, treeMap, nodes, routes, threads, meta) {
    S.sigs = sigs;
    S.nodes = nodes;
    S.meta = meta;
    S.threadDefs = threads.threads;

    Object.keys(sigs).forEach(function (id) {
      sigs[id].forEach(function (t) {
        var k = t.toLowerCase();
        (S.tokenIdx[k] = S.tokenIdx[k] || []).push(id);
      });
    });

    S.roots = Object.keys(nodes).filter(function (k) {
      return nodes[k].p === null;
    });
    S.roots.push('unplaced');

    S.pts = idx.items
      .filter(function (t) {
        return geo[t.id];
      })
      .map(function (t) {
        var g = geo[t.id];
        var p = proj(g[0], g[1]);
        var node = treeMap[t.id] || null;
        var root = node ? node.split('.')[0] : 'unplaced';
        return {
          id: t.id,
          name: t.name.replace(/&amp;/g, '&'),
          node: node,
          root: root,
          lat: g[0],
          lng: g[1],
          place: g[2],
          // Sidebar bucket, from the table in scripts/_atlas_regions.js.
          region: g[3],
          x: p[0],
          y: p[1],
        };
      });
    S.pts.forEach(function (p) {
      S.byId[p.id] = p;
      S.rootCount[p.root] = (S.rootCount[p.root] || 0) + 1;
    });

    // Largest groups first get the plainest glyph (a circle); hues cycle
    // before shapes, so no two roots share a (hue, shape) pair until there
    // are more roots than HUES x SHAPES.
    S.roots = S.roots.filter(function (r) {
      return S.rootCount[r];
    });
    S.roots
      .slice()
      .sort(function (a, b) {
        return S.rootCount[b] - S.rootCount[a] || (a < b ? -1 : 1);
      })
      .forEach(function (r, i) {
        S.style[r] = {
          hue: HUES[i % HUES.length],
          shape: SHAPES[Math.floor(i / HUES.length) % SHAPES.length],
        };
      });

    S.land = new Path2D();
    var addRing = function (ring) {
      ring.forEach(function (c, i) {
        var p = proj(c[1], c[0]);
        if (i === 0) S.land.moveTo(p[0], p[1]);
        else S.land.lineTo(p[0], p[1]);
      });
      S.land.closePath();
    };
    world.features.forEach(function (f) {
      if (!f.geometry) return;
      if (f.geometry.type === 'Polygon') f.geometry.coordinates.forEach(addRing);
      else if (f.geometry.type === 'MultiPolygon')
        f.geometry.coordinates.forEach(function (poly) {
          poly.forEach(addRing);
        });
    });

    S.routes = routes.routes
      .map(function (r) {
        var end = function (e) {
          if (typeof e === 'string') return S.byId[e];
          var pr = proj(e[0], e[1]);
          return { x: pr[0], y: pr[1], name: e[2] };
        };
        var a = end(r.a),
          b = end(r.b);
        return a && b ? { ax: a.x, ay: a.y, bx: b.x, by: b.y, a: a, b: b, label: r.label } : null;
      })
      .filter(Boolean);
  }

  // The image manifest is optional and comes from a separate pipeline. Only an
