#!/usr/bin/env python3
"""The Lyrics page's type menu, derived from the relation registry.

The page (src/pages/lyrics.js, LY_TYPES) lists every registry type an English
song can use, with the type's REGISTRY INDEX (its position in
`relations.REGISTRY`). The index is what the page sends to the writer; the
name is shown to the person only.

A type is listed when all of these hold:
  * its `normative` is "attested" (a forbidden or deprecated type is never
    offered);
  * it is not one of the four types the owner disowned for English songs
    (homoioteleuton, trite rhyme, cynghanedd sain drosgl, fourth lift must
    not alliterate);
  * one of its traditions is English (`lang == "eng"`): a type that is not
    specifically for English does not count for English;
  * every capability it needs is supplied by a plain English song stream
    (sections and stanzas declared, nothing else), so the grader can judge it.

This mirrors the planner's eligible set until the planner exports its own;
a type the planner refuses is refused there by name, never substituted.

Usage (from the repository root):
  python3 scripts/lyric_type_menu.py           # print the JS rows
  python3 scripts/lyric_type_menu.py --check   # exit 1 when lyrics.js differs
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HARNESS = os.path.join(ROOT, "lyric-harness")
PAGE = os.path.join(ROOT, "src", "pages", "lyrics.js")
DISOWNED = ("homoioteleuton", "trite rhyme", "cynghanedd sain drosgl",
            "fourth lift must not alliterate")
BEGIN = "// LY_TYPES BEGIN (generated by scripts/lyric_type_menu.py)"
END = "// LY_TYPES END"


def eligible():
    sys.path.insert(0, HARNESS)
    from quality import relations as R
    from quality.phonology import get as get_phonology
    lines = ["one", "two", "three", "four"]
    st = R.build_stream(lines, get_phonology("eng"), sections=["S"] * 4,
                        stanzas=[0] * 4, stanza_source="declared_sections",
                        declaration={"language": "eng"})
    out = []
    for index, (name, schema) in enumerate(R.REGISTRY.items()):
        if schema.normative != "attested" or name in DISOWNED:
            continue
        if not any(getattr(t, "lang", "") == "eng" for t in schema.traditions):
            continue
        if any(st.supply(c).state != "present" for c in schema.capabilities()):
            continue
        out.append((index, name))
    return out


def js_string(text):
    """A JS string literal as the repository's formatter writes it."""
    if "'" in text and '"' not in text:
        return '"' + text.replace("\\", "\\\\") + '"'
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def rows():
    body = "\n".join(f"  [{i}, {js_string(n)}],"
                     for i, n in eligible())
    return f"{BEGIN}\nconst LY_TYPES = [\n{body}\n];\n{END}"


def main():
    want = rows()
    if "--check" not in sys.argv:
        print(want)
        return 0
    with open(PAGE, encoding="utf-8") as f:
        page = f.read()
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), page, re.S)
    if not m:
        print("lyric type menu: FAIL — LY_TYPES markers missing in lyrics.js")
        return 1
    if m.group(0) != want:
        print("lyric type menu: FAIL — LY_TYPES in src/pages/lyrics.js differs "
              "from the registry; run python3 scripts/lyric_type_menu.py and "
              "paste its output between the markers.")
        return 1
    print(f"lyric type menu: PASS — {want.count('],')} eligible types match "
          f"the registry")
    return 0


if __name__ == "__main__":
    sys.exit(main())
