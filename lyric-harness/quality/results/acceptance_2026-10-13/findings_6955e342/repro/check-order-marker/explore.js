'use strict';
const C = require('./com.js');
const TREE = process.argv[2] || 'cand';
const BODY = `[VERSE]\nOh--oh, oh my love\nI walk the line tonight\nI hold you tight\nWell-worn shoes upon the floor\nThe rain comes down\nI hear the sound\nThe night is cold\nLove above\n\n[BRIDGE]\nGo slow\nHold on\n\n[BRIDGE]\nGo slow\nHold on`;
(async () => {
  const { server, base } = await C.startServer(TREE);
  const browser = await C.launch();
  const { page, q, errors } = await C.boot(browser, base);
  await C.enterBody(page, BODY);
  console.log('after body', JSON.stringify(await C.draftText(page)).slice(0, 80), await C.hist(page).then(h=>[h.idx,h.n]));
  await C.insertAtTop(page, '[SETUP — rhyme groups — 1.T4,8; 2,3]\n\n', 'paste');
  console.log('after paste:', JSON.stringify((await C.draftText(page)).split('\n').slice(0, 3)), await C.toasts(page));
  console.log('sections returnOf', await page.evaluate(() => LY.model.sections.map(s => [s.title, s.returnOf && s.returnOf.title])));
  await C.openTool(page, 'rhymes');
  console.log('radios', await page.locator('input[name="ly-link-group"]').count(), await page.evaluate(() => [...document.querySelectorAll('.ly-links li')].map(l => l.innerText.replace(/\s+/g,' '))));
  await page.locator('input[name="ly-link-group"][value="1"]').check();
  await page.waitForTimeout(200);
  await page.locator('[data-ui="ly-link-remove"]').click();
  await page.waitForTimeout(400);
  console.log('after remove:', JSON.stringify((await C.draftText(page)).split('\n').slice(0, 3)), await C.toasts(page));
  console.log('links', await page.evaluate(() => [...document.querySelectorAll('.ly-links li')].map(l => l.innerText.replace(/\s+/g,' '))));
  await page.locator('.ly-run').first().click();
  await C.idle(page);
  console.log('calls', q.calls.length, JSON.stringify(q.calls.map(c => c.lyric_context && c.lyric_context.declarations)));
  console.log('after send:', JSON.stringify((await C.draftText(page)).split('\n').slice(0, 3)), await C.toasts(page));
  console.log('state', await page.evaluate(() => ({busy: chatState.busy, pending: !!chatState.pending, live: lyLiveWork()})));
  console.log('call keys', Object.keys(q.calls[0]||{}), Object.keys((q.calls[0]||{}).lyric_context||{}));
  console.log('errors', errors);
  await browser.close(); server.close();
})().catch(e => (console.error(e), process.exit(1)));
