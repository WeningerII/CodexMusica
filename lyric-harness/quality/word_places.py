#!/usr/bin/env python3
"""WHERE REAL WORDS SIT IN A SUNG LINE: the table the planner picks a tied
word's place from.

    python3 quality/word_places.py --check    # recount; exit 1 if it moved
    python3 quality/word_places.py --write    # rewrite data/word_places_en.tsv

WHY THIS EXISTS (owner's rulings, 2026-11-23). A rhyme tie inside a line
names its word by number ("word 9 of line 4"), and that number forces the line
to be at least that long. The planner picked it evenly up to a ceiling of 7
words, the floor's average line length, so a deep word was never asked. The
owner took that ceiling out and ruled that the pick follows where real words
sit instead: a place is picked as often as real sung lines have a word there,
up to the longest line the corpus holds. That is the ONE written exception to
the move-37 rule that the corpus samples nothing (`quality/plan.py`'s module
docstring), made knowing its cost: word 15 comes up about 1 time in 9,000 and
word 22 about 1 time in a million.

WHAT IS COUNTED. Every sung line of `corpus/song/eng_*.txt`, by K-1's rule
(`quality/phrase_commonplace.sung_lines`, reused so the two cannot drift
apart). Its words are numbered exactly as a placement numbers them:
`slots._token_runs` over `word_syllable_map`, so a word the dictionary cannot
read gets no number, here as in a plan. The table holds, for each word count,
how many lines have exactly that many words. `plan.py` reads it and derives
the rest: the lines with a word at place k are the lines with k or more words,
and the longest line is the largest count the table holds.

The table is generated, never typed: `--check` recounts the corpus (about two
minutes) and fails if any number moved, so adding songs to the corpus moves
the table only through `--write`, in a commit that says so.
"""

import argparse
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

TABLE = os.path.join(ROOT, "data", "word_places_en.tsv")
CORPUS = os.path.join(ROOT, "corpus", "song", "eng_*.txt")

HEADER = """\
# WORD PLACES over corpus/song/eng_*: how many sung lines have exactly n words.
#
# Generated by quality/word_places.py --write; quality/word_places.py --check
# recounts the corpus and fails if any number moved. Declared in
# data/sources.tsv. A sung line is K-1's (phrase_commonplace.sung_lines); its
# words are numbered as a placement numbers them (slots._token_runs over
# word_syllable_map), so a word the dictionary cannot read is not counted.
# quality/plan.py picks a tied word's place inside a line from this table
# (owner's ruling, 2026-11-23).
#
words\tlines
"""


def count():
    """-> {word count: number of sung lines with exactly that many words}."""
    import lyric_harness as LH
    from quality import slots as SL
    from quality.phrase_commonplace import sung_lines
    lex = LH.Lexicon()
    out = {}
    for path in sorted(glob.glob(CORPUS)):
        for line in sung_lines(path):
            n = len(SL._token_runs(LH.word_syllable_map(lex, line)))
            out[n] = out.get(n, 0) + 1
    return out


def render(counts):
    rows = "".join(f"{n}\t{counts.get(n, 0)}\n"
                   for n in range(0, max(counts) + 1))
    return HEADER + rows


def read(path=TABLE):
    """-> {word count: lines}, as the table holds it."""
    out = {}
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            if raw.startswith("#") or not raw.strip() or raw.startswith("words"):
                continue
            n, lines = raw.rstrip("\n").split("\t")
            out[int(n)] = int(lines)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    counts = count()
    text = render(counts)
    if args.write:
        with open(TABLE, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(TABLE, ROOT)}: {sum(counts.values())} "
              f"lines, longest {max(counts)} words")
        return 0
    try:
        with open(TABLE, encoding="utf-8") as fh:
            held = fh.read()
    except FileNotFoundError:
        held = None
    if held == text:
        print(f"word places table matches the corpus: {sum(counts.values())} "
              f"lines, longest {max(counts)} words")
        return 0
    have = read() if held is not None else {}
    moved = [(n, have.get(n), counts.get(n))
             for n in sorted(set(have) | set(counts))
             if have.get(n) != counts.get(n)]
    print("word places table is out of date: (words, table, corpus) "
          f"{moved[:10]}\nremedy: python3 quality/word_places.py --write, "
          "in a commit that says the corpus moved it")
    return 1


if __name__ == "__main__":
    sys.exit(main())
